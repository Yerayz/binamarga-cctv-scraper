const index = '<div class="bpjn-box"><a href="?id_ruas=road">Road</a><h1>Road &amp; II</h1><div class="text-orange">4 online</div></div>';
const cameras = '<div class="card-cctv"><video id="my_video_1"><source src="https://camera.example.com/hls/index.m3u8"></video><h5>KM 1</h5></div>';
const fixture = () => new Catalog({ fetchPage: async url => url.includes('?') ? cameras : index });
const listen = app => new Promise(resolve => { const server = app.listen(0, '127.0.0.1', () => resolve(server)); });
const base = server => `http://127.0.0.1:${server.address().port}`;
const wait = async fn => { for (let i = 0; i < 400; i++) { if (fn()) return; await new Promise(r => setTimeout(r, 50)); } throw new Error('Timed out waiting for recording'); };

test('publisher discovery, duplicates, cache and URL validation', async () => {
  assert.deepEqual(parseRoads(index), [{ id: 'road', name: 'Road & II', listed: 4 }]);
  assert.equal(parseCameras(cameras + cameras, 'road').length, 1);
  for (const url of ['http://127.0.0.1/x', 'http://192.168.1.2/x', 'http://[::1]/x', 'https://localhost/x', 'http://user:pass@example.com/x', 'file:///etc/passwd']) assert.equal(publicUrl(url), false);
  assert.equal(publicUrl('https://camera.example.com/x'), true);
  let calls = 0;
  const catalog = new Catalog({ fetchPage: async url => { calls++; return url.includes('?') ? cameras : index; } });
  await catalog.cameras('road'); await catalog.cameras('road'); assert.equal(calls, 2);
  await assert.rejects(catalog.cameras('unknown'), /Road not found/);
  await assert.rejects(catalog.resolve('road', 'my_video_1', 'Wrong camera'), /Camera not found/);
});
test('playlist relay rejects traversal and rewrites keys and nested segments', () => {
  const url = 'https://camera.example.com/hls/index.m3u8';
  for (const target of ['http://localhost/private', 'https://camera.example.com/other/a.ts', 'https://camera.example.com/hls/../private', 'https://camera.example.com/hls/%2e%2e/private', 'https://camera.example.com/hls/%5cprivate']) assert.throws(() => resourceUrl(url, target));
  const result = rewritePlaylist('#EXTM3U\n#EXT-X-KEY:URI="key.bin"\nsegment.ts\n', url, url, '/relay');
  assert.match(result, /URI="\/relay\?url=/); assert.match(result, /segment.ts/);
});
test('cron uses Jakarta timezone and validates malformed expressions', () => {
  assert.equal(nextRun('0 8 * * *', 'Asia/Jakarta', new Date('2026-01-01T00:00:00Z')), '2026-01-01T01:00:00.000Z');
  assert.throws(() => nextRun('invalid', 'Asia/Jakarta'));
});
test('authentication, task CRUD, downloads, deletion and legacy metadata import', async t => {
  const dir = await mkdtemp(path.join(tmpdir(), 'tolwatch-api-'));
  const clips = path.join(dir, 'clips'); await mkdir(clips);
  await writeFile(path.join(clips, 'old.mp4'), 'sample video');
  await writeFile(path.join(clips, `${'a'.repeat(32)}.json`), JSON.stringify({ id: 'a'.repeat(32), status: 'completed', filename: 'old.mp4', createdAt: new Date().toISOString(), cameraName: 'Old', roadName: 'Road' }));
  const store = new Store(path.join(dir, 'data'), clips);
  const catalog = fixture(), engine = new Engine({ store, catalog, directory: clips, minFreeBytes: 0 }); await engine.init();
  const server = await listen(createApp({ store, catalog, engine, password: 'test-password' }));
  t.after(async () => { await engine.shutdown(); await new Promise(r => server.close(r)); store.close(); await rm(dir, { recursive: true, force: true }); });
  const url = base(server);
  assert.equal((await fetch(url + '/api/roads')).status, 401);
  assert.equal((await fetch(url + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ password: 'bad' }) })).status, 401);
  const login = await fetch(url + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ password: 'test-password' }) });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const request = (route, method = 'GET', body) => fetch(url + route, { method, headers: { cookie, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await request('/api/roads')).status, 200);
  assert.equal((await fetch(url + '/api/tasks', { method: 'POST', headers: { cookie, Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  let response = await request('/api/tasks', 'POST', { roadId: 'road', cameraId: 'my_video_1', mode: 'scheduled', duration: 60, cron: '0 * * * *', enabled: false });
  assert.equal(response.status, 201); const task = await response.json();
  assert.equal((await request(`/api/tasks/${task.id}`, 'PATCH', { enabled: true })).status, 200);
  assert.equal((await request(`/api/tasks/${task.id}`, 'DELETE')).status, 200);
  response = await request(`/api/recordings/${'a'.repeat(32)}/download`); assert.equal(await response.text(), 'sample video'); assert.match(response.headers.get('content-disposition'), /attachment/);
  assert.equal((await request(`/api/recordings/${'a'.repeat(32)}`, 'DELETE')).status, 200);
  assert.equal(store.list('records').length, 0);
  const again = new Store(path.join(dir, 'other'), clips); assert.equal(again.list('records').length, 0); again.close();
});
test('FFmpeg preserves source resolution and codec; continuous segments finalize and tasks recover', async t => {
  const dir = await mkdtemp(path.join(tmpdir(), 'tolwatch-video-'));
  await exec('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=320x180:rate=10', '-t', '24', '-c:v', 'libx264', '-g', '20', '-preset', 'ultrafast', '-f', 'hls', '-hls_time', '2', '-hls_list_size', '0', '-y', path.join(dir, 'source.m3u8')]);
  const sourceApp = express(); sourceApp.use(express.static(dir)); const sourceServer = await listen(sourceApp);
  const stream = base(sourceServer) + '/source.m3u8';
  const catalog = { resolve: async () => ({ road: { id: 'road', name: 'Road' }, camera: { id: 'cam', name: 'Camera', url: stream }, sourceUrl: base(sourceServer) }) };
  const clips = path.join(dir, 'clips'), store = new Store(path.join(dir, 'data'), clips);
  const engine = new Engine({ store, catalog, directory: clips, minFreeBytes: 0 }); await engine.init(); clearInterval(engine.timer);
  t.after(async () => { await engine.shutdown(); await new Promise(r => sourceServer.close(r)); store.close(); await rm(dir, { recursive: true, force: true }); });
  await writeFile(path.join(dir, 'master.m3u8'), '#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=100000,RESOLUTION=160x90\nlow.m3u8\n#EXT-X-STREAM-INF:BANDWIDTH=200000,RESOLUTION=320x180\nsource.m3u8\n');
  assert.equal(await highestVariant(base(sourceServer) + '/master.m3u8', base(sourceServer)), stream);
  const job = await engine.start('road', 'cam', 10);
  await assert.rejects(engine.start('road', 'cam', 10), /already recording/);
  await wait(() => engine.active.size === 0);
  const saved = store.get('records', job.id); assert.equal(saved.status, 'completed', saved.error); assert.equal(saved.width, 320); assert.equal(saved.height, 180); assert.equal(saved.codec, 'h264');
  const task = await engine.saveTask({ roadId: 'road', cameraId: 'cam', mode: 'continuous', duration: 10, enabled: false });
  await engine.runTask(task); await wait(() => engine.active.size === 0);
  const segments = store.list('records').filter(j => j.mode === 'continuous'); assert.ok(segments.length >= 2);
  for (const segment of segments) { assert.equal(segment.width, 320); assert.equal(segment.codec, 'h264'); assert.ok(segment.bytes > 0); }
  const scheduled = await engine.saveTask({ roadId: 'road', cameraId: 'cam', mode: 'scheduled', duration: 10, cron: '* * * * *', enabled: true });
  scheduled.nextRun = '2000-01-01T00:00:00Z'; store.save('tasks', scheduled);
  await engine.tick(); await wait(() => engine.active.size === 0);
  assert.ok(store.events(scheduled.id).some(event => event.status === 'completed'));
  const pending = { ...saved, id: 'b'.repeat(32), status: 'recording', filename: 'missing.mp4' }; store.save('records', pending);
  await engine.shutdown();
  const recovered = new Engine({ store, catalog, directory: clips, minFreeBytes: 0 }); await recovered.init(); clearInterval(recovered.timer); await recovered.shutdown();
  assert.equal(store.get('records', pending.id).status, 'failed');
});
